defmodule AshGrpc.DataLayer.Foreign do
  @moduledoc """
  IR for compiled protobuf modules that were not built from Ash resources.

  `AshGrpc.Codec` works on `AshGrpc.Proto.IR` messages. Messages of foreign services (imported
  with `use AshGrpc.Protos`, `mix ash_grpc.import`, or generated by `protoc-gen-elixir` with
  `gen_descriptors=true`) are plain `use Protobuf` modules, so this module rebuilds their IR from
  the descriptors they carry:

    1. the message module and every message/enum module it references (transitively, through
       `__message_props__/0`) are collected,
    2. each module's `descriptor/0` is wrapped into a `FileDescriptorProto` (the package is
       derived from `full_name/0`) and the set is mapped with
       `AshGrpc.Proto.Import.from_descriptor_set/2`,
    3. the `module` of every IR message/enum is set to the actual Elixir module, and field
       sources are cleared (`nil`), so the codec uses the proto field names and natural
       conversions (see "Field sources" in `AshGrpc.Codec`).

  Modules without `descriptor/0` (well-known types such as `Google.Protobuf.Timestamp`, and
  `google.type.*` from `googleapis`) are left out: the codec knows them already.

  Results are cached in `:persistent_term`, keyed by the module and its MD5, so a recompiled
  module gets a fresh IR.
  """

  alias AshGrpc.Proto.{Import, IR}

  @doc """
  Returns the IR message of the protobuf `module` and the schema containing it and every type
  it references.
  """
  @spec message(module()) :: {:ok, IR.Message.t(), IR.Schema.t()} | {:error, term()}
  def message(module) when is_atom(module) do
    with {:ok, schema} <- schema(module) do
      case IR.Schema.lookup(schema, module.full_name()) do
        {:ok, %IR.Message{} = message} -> {:ok, message, schema}
        _ -> {:error, {:not_a_message, module}}
      end
    end
  end

  @doc "Like `message/1`, but raises `ArgumentError` on errors."
  @spec message!(module()) :: {IR.Message.t(), IR.Schema.t()}
  def message!(module) do
    case message(module) do
      {:ok, message, schema} ->
        {message, schema}

      {:error, reason} ->
        raise ArgumentError,
              "cannot build the IR of #{inspect(module)}: #{inspect(reason)}"
    end
  end

  @doc """
  Returns the IR schema of the protobuf `module` (a message or enum) and every message/enum
  module it references. Cached in `:persistent_term`.
  """
  @spec schema(module()) :: {:ok, IR.Schema.t()} | {:error, term()}
  def schema(module) when is_atom(module) do
    with :ok <- check_module(module) do
      key = {__MODULE__, module, module.module_info(:md5)}

      case :persistent_term.get(key, nil) do
        nil -> module |> build() |> cache(key)
        schema -> {:ok, schema}
      end
    end
  end

  defp cache({:ok, schema}, key) do
    :persistent_term.put(key, schema)
    {:ok, schema}
  end

  defp cache(error, _key), do: error

  @doc """
  Builds the schema of `module` without the cache (see `schema/1`).
  """
  @spec build(module()) :: {:ok, IR.Schema.t()} | {:error, term()}
  def build(module) do
    with :ok <- check_module(module) do
      modules = closure([module], MapSet.new(), [])
      by_name = Map.new(modules, &{&1.full_name(), &1})

      files =
        modules
        |> Enum.filter(&function_exported?(&1, :descriptor, 0))
        |> drop_nested(by_name)
        |> Enum.map(&file_descriptor/1)

      with {:ok, schema} <-
             Import.from_descriptor_set(%Google.Protobuf.FileDescriptorSet{file: files},
               validate_types?: false
             ) do
        {:ok, put_modules(schema, by_name)}
      end
    end
  end

  defp check_module(module) do
    cond do
      not Code.ensure_loaded?(module) -> {:error, {:not_loaded, module}}
      not function_exported?(module, :__message_props__, 0) -> {:error, {:not_protobuf, module}}
      not function_exported?(module, :descriptor, 0) -> {:error, {:no_descriptor, module}}
      true -> :ok
    end
  end

  # every message/enum module reachable from the given ones (map entries are traversed but
  # not returned: they are part of their parent's descriptor)
  defp closure([], _seen, acc), do: Enum.reverse(acc)

  defp closure([module | rest], seen, acc) do
    if MapSet.member?(seen, module) or not Code.ensure_loaded?(module) or
         not function_exported?(module, :__message_props__, 0) do
      closure(rest, seen, acc)
    else
      props = module.__message_props__()
      seen = MapSet.put(seen, module)

      referenced =
        for {_tag, field} <- props.field_props,
            field.embedded? or field.enum?,
            type = referenced_type(field.type),
            not is_nil(type),
            do: type

      acc = if props.map?, do: acc, else: [module | acc]
      closure(referenced ++ rest, seen, acc)
    end
  end

  defp referenced_type({:enum, module}) when is_atom(module), do: module

  defp referenced_type(module) when is_atom(module) and module not in [nil, true, false],
    do: module

  defp referenced_type(_type), do: nil

  # nested types are already part of the descriptor of the type that contains them
  defp drop_nested(modules, by_name) do
    Enum.reject(modules, fn module ->
      module.full_name()
      |> parents()
      |> Enum.any?(&Map.has_key?(by_name, &1))
    end)
  end

  defp parents(full_name) do
    segments = String.split(full_name, ".")

    for n <- 1..(length(segments) - 1)//1, do: segments |> Enum.take(n) |> Enum.join(".")
  end

  defp file_descriptor(module) do
    descriptor = module.descriptor()
    full_name = module.full_name()

    package =
      full_name
      |> String.trim_trailing(descriptor.name)
      |> String.trim_trailing(".")

    path = Path.join(String.split(package, ".", trim: true) ++ [descriptor.name <> ".proto"])
    enum? = module.__message_props__().enum?

    %Google.Protobuf.FileDescriptorProto{
      name: path,
      package: if(package == "", do: nil, else: package),
      syntax: syntax(module),
      message_type: if(enum?, do: [], else: [descriptor]),
      enum_type: if(enum?, do: [descriptor], else: [])
    }
  end

  defp syntax(module) do
    case module.__message_props__().syntax do
      :proto2 -> "proto2"
      _ -> "proto3"
    end
  end

  defp put_modules(%IR.Schema{files: files} = schema, by_name) do
    %{
      schema
      | files:
          Enum.map(files, fn file ->
            %{
              file
              | messages: Enum.map(file.messages, &put_message_module(&1, by_name)),
                enums: Enum.map(file.enums, &put_module(&1, by_name))
            }
          end)
    }
  end

  defp put_message_module(message, by_name) do
    %{
      put_module(message, by_name)
      | fields: Enum.map(message.fields, &%{&1 | source: nil}),
        nested_messages: Enum.map(message.nested_messages, &put_message_module(&1, by_name)),
        nested_enums: Enum.map(message.nested_enums, &put_module(&1, by_name))
    }
  end

  defp put_module(entity, by_name) do
    case Map.fetch(by_name, entity.full_name) do
      {:ok, module} -> %{entity | module: module}
      :error -> entity
    end
  end
end
