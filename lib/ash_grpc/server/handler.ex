defmodule AshGrpc.Server.Handler do
  @moduledoc """
  The default rpc handler: turns a decoded request into Ash calls and the result into a reply
  (DESIGN.md §4.4). The `GRPC.Server` modules generated by `AshGrpc.Endpoint` call `handle/4`.

  | kind | Ash call |
  |---|---|
  | `:get` | `Ash.read_one/2` (`get_by` fields as filter, arguments as action input); `NOT_FOUND` when nil |
  | `:list` | `Ash.read/2` with a page (see `AshGrpc.Server.Pagination`) |
  | `:server_stream` | `Ash.stream!/2`, one reply per record, with backpressure |
  | `:create` | `Ash.create/2` |
  | `:update` | the record is read by primary key, then `Ash.update/2` (atomic when the action allows it); `update_mask` limits the changed inputs |
  | `:destroy` | the record is read by primary key, then `Ash.destroy/2`; replies `Empty` or the destroyed record |
  | `:client_stream` | `Ash.bulk_create/4` in batches; replies `{count, errors}` |
  | `:action` | `Ash.run_action/2`; `Empty`, the message itself or a `{value}` wrapper |

  Every Ash call gets the actor, tenant and context stored by interceptors (see
  `AshGrpc.Server`) and the remaining deadline as `timeout`; the deadline is also propagated to
  `AshGrpc.Client` calls made while handling the request (`AshGrpc.Client.put_deadline/1`).

  Errors are converted with `AshGrpc.Error.to_rpc_error/2` (passing the request message, so
  `BadRequest` field violations use proto field names).

  ## Telemetry

    * `[:ash_grpc, :server, :rpc, :start]` – metadata `%{endpoint, service, rpc, resource,
      action, kind, actor, tenant}`
    * `[:ash_grpc, :server, :rpc, :stop]` – adds `:status` (`:ok` or the snake_case gRPC
      status) and `:error` (the `GRPC.RPCError`, when failed)
    * `[:ash_grpc, :server, :rpc, :exception]` – when the handler process exits abnormally
  """

  alias AshGrpc.Codec
  alias AshGrpc.Proto.IR
  alias AshGrpc.Server.{Context, Masks, Pagination}

  require Logger

  @event [:ash_grpc, :server, :rpc]
  @empty "google.protobuf.Empty"

  # replies queued in the connection process before a server stream waits (backpressure)
  @max_pending_replies 32

  @doc """
  Handles one rpc of `endpoint`. `key` is `{service_full_name, rpc_name}`.

  Returns the reply (unary responses) or the stream (streaming responses); raises
  `GRPC.RPCError` on failure.
  """
  @spec handle(module(), {String.t(), String.t()}, term(), AshGrpc.Types.server_stream()) ::
          term()
  def handle(endpoint, key, request, stream) do
    ctx = Context.new(endpoint, endpoint.__ash_grpc__({:rpc, key}), stream)
    if ctx.timeout, do: AshGrpc.Client.put_deadline(ctx.timeout)

    metadata = %{
      endpoint: endpoint,
      service: ctx.service,
      rpc: ctx.rpc.name,
      resource: ctx.resource,
      action: ctx.action && ctx.action.name,
      kind: ctx.kind,
      actor: ctx.actor,
      tenant: ctx.tenant
    }

    result =
      :telemetry.span(@event, metadata, fn ->
        result = execute(ctx, request)
        {result, Map.merge(metadata, stop_metadata(result))}
      end)

    case result do
      {:ok, reply} -> reply
      {:error, %GRPC.RPCError{} = error} -> raise error
    end
  end

  defp stop_metadata({:ok, _}), do: %{status: :ok}

  defp stop_metadata({:error, error}),
    do: %{status: AshGrpc.Error.Info.code(error.status), error: error}

  defp execute(%Context{timeout: 0} = ctx, _request),
    do: {:error, to_rpc_error(Ash.Error.Invalid.Timeout.exception(name: ctx.rpc.name), ctx)}

  defp execute(ctx, request) do
    {:ok, run(ctx, request)}
  rescue
    error in GRPC.RPCError ->
      {:error, error}

    error ->
      rpc_error = to_rpc_error(error, ctx)

      if rpc_error.status == GRPC.Status.internal() do
        Logger.error(fn ->
          "#{ctx.service}/#{ctx.rpc.name} failed: " <>
            Exception.format(:error, error, __STACKTRACE__)
        end)
      end

      {:error, rpc_error}
  end

  ## Dispatch

  defp run(%Context{config: %{handler: handler}} = ctx, request) when not is_nil(handler) do
    case handler.handle_rpc(request, ctx.stream, ctx) do
      {:ok, reply} -> reply
      {:error, error} -> raise to_rpc_error(error, ctx)
      reply -> reply
    end
  end

  defp run(%Context{kind: :get} = ctx, request) do
    input = decode!(request, ctx.input, ctx)
    {by, args} = split_get_by(input, ctx)

    ctx.resource
    |> Ash.Query.for_read(ctx.action.name, args, Context.input_opts(ctx))
    |> Ash.Query.do_filter(by)
    |> Masks.apply_read_mask(request, ctx)
    |> Ash.read_one(Context.call_opts(ctx))
    |> case do
      {:ok, nil} -> not_found!(ctx, by)
      {:ok, record} -> reply_record!(record, ctx)
      {:error, error} -> raise error
    end
  end

  defp run(%Context{kind: :list} = ctx, request) do
    input = decode!(request, ctx.input, ctx)

    {records, next, total} =
      ctx.resource
      |> Ash.Query.for_read(ctx.action.name, input, Context.input_opts(ctx))
      |> Masks.apply_filter(request, ctx)
      |> Masks.apply_read_mask(request, ctx)
      |> Pagination.read(request, ctx)

    items = Enum.map(records, &encode_record!(&1, ctx))
    special_struct(ctx, %{items: items, next_page_token: next, total_size: total})
  end

  defp run(%Context{kind: :server_stream} = ctx, request) do
    input = decode!(request, ctx.input, ctx)

    opts =
      ctx
      |> Context.call_opts()
      |> Keyword.delete(:timeout)
      |> Keyword.merge(batch_size: ctx.settings.stream_batch_size, allow_stream_with: :full_read)

    ctx.resource
    |> Ash.Query.for_read(ctx.action.name, input, Context.input_opts(ctx))
    |> Masks.apply_read_mask(request, ctx)
    |> Ash.stream!(opts)
    |> Enum.each(fn record ->
      await_capacity(ctx.stream)
      GRPC.Server.send_reply(ctx.stream, encode_record!(record, ctx))
    end)

    ctx.stream
  end

  defp run(%Context{kind: :create} = ctx, request) do
    input = decode_input!(request, ctx, nil)

    ctx.resource
    |> Ash.Changeset.for_create(ctx.action.name, input, Context.input_opts(ctx))
    |> Ash.create(Keyword.put(Context.call_opts(ctx), :load, Masks.default_load(ctx)))
    |> case do
      {:ok, record} -> reply_record!(record, ctx)
      {:error, error} -> raise error
    end
  end

  defp run(%Context{kind: :update} = ctx, request) do
    paths = if ctx.config.update_mask?, do: Masks.update_paths(request, update_target(ctx))
    input = decode_input!(request, ctx, paths)
    {pk, input} = split_primary_key(input, ctx)

    ctx
    |> fetch_record!(pk)
    |> Ash.Changeset.for_update(ctx.action.name, input, Context.input_opts(ctx))
    |> Ash.update(Keyword.put(Context.call_opts(ctx), :load, Masks.default_load(ctx)))
    |> case do
      {:ok, record} -> reply_record!(record, ctx)
      {:error, error} -> raise error
    end
  end

  defp run(%Context{kind: :destroy} = ctx, request) do
    input = decode!(request, ctx.input, ctx)
    {pk, args} = split_primary_key(input, ctx)

    ctx
    |> fetch_record!(pk)
    |> Ash.Changeset.for_destroy(ctx.action.name, args, Context.input_opts(ctx))
    |> Ash.destroy(Keyword.put(Context.call_opts(ctx), :return_destroyed?, true))
    |> case do
      {:ok, record} -> if ctx.rpc.output == @empty, do: empty(), else: reply_record!(record, ctx)
      {:error, error} -> raise error
    end
  end

  defp run(%Context{kind: :client_stream} = ctx, requests) do
    batch_size = ctx.settings.stream_batch_size

    {count, errors} =
      requests
      |> Stream.chunk_every(batch_size)
      |> Enum.reduce({0, []}, fn chunk, {count, errors} ->
        {inputs, decode_errors} = decode_chunk(chunk, ctx)
        {created, create_errors} = bulk_create(inputs, ctx)
        {count + created, errors ++ decode_errors ++ create_errors}
      end)

    special_struct(ctx, %{count: count, errors: errors})
  end

  defp run(%Context{kind: :action} = ctx, request) do
    input = decode!(request, ctx.input, ctx)

    ctx.resource
    |> Ash.ActionInput.for_action(ctx.action.name, input, Context.input_opts(ctx))
    |> Ash.run_action(Keyword.delete(Context.call_opts(ctx), :timeout))
    |> case do
      :ok -> empty()
      {:ok, value} -> reply_value!(value, ctx)
      {:error, error} -> raise error
    end
  end

  defp run(%Context{} = ctx, _request) do
    raise GRPC.RPCError,
      status: GRPC.Status.unimplemented(),
      message: "#{ctx.rpc.name} (#{ctx.kind}) requires a `handler:`"
  end

  ## Requests

  @doc """
  Decodes a request struct with the IR message (or field by field for hand-written request
  modules) into a map keyed by Ash names; raises `INVALID_ARGUMENT` on invalid values.
  """
  @spec decode!(struct(), IR.Message.t() | nil, Context.t(), Keyword.t()) :: map()
  def decode!(request, message, ctx, opts \\ [])

  def decode!(request, nil, _ctx, _opts) do
    request |> Map.from_struct() |> Map.delete(:__unknown_fields__)
  end

  def decode!(request, %IR.Message{} = message, ctx, opts) do
    case Codec.decode_message(request, message, ctx.schema, opts) do
      {:ok, input} -> input || %{}
      {:error, reason} -> raise codec_error(reason)
    end
  end

  # flat or wrapped (`{ User user = 1; <arguments> }`) create/update input
  defp decode_input!(request, ctx, paths) do
    case Enum.find(fields(ctx.input), &(&1.source == {:special, :record})) do
      nil ->
        decode!(request, ctx.input, ctx, present_opts(paths))
        |> restrict(ctx.input, paths)

      field ->
        args = decode!(request, ctx.input, ctx)

        record =
          request
          |> Map.get(String.to_existing_atom(field.name))
          |> case do
            nil -> %{}
            nested -> decode!(nested, ctx.record, ctx, present_opts(paths))
          end
          |> restrict(ctx.record, paths)
          |> Map.take(accepted(ctx))

        Map.merge(args, record)
    end
  end

  defp update_target(ctx) do
    if Enum.any?(fields(ctx.input), &(&1.source == {:special, :record})),
      do: ctx.record,
      else: ctx.input
  end

  defp present_opts(nil), do: []
  defp present_opts(paths), do: [present: paths]

  # with an update mask only masked fields (and arguments / primary key) are kept
  defp restrict(input, _message, nil), do: input

  defp restrict(input, message, paths) do
    pk = message_pk(message)

    keep =
      for %IR.Field{name: proto_name, source: source} <- fields(message),
          proto_name in paths or argument?(source) or ash_name(source) in pk,
          do: ash_name(source)

    Map.take(input, keep)
  end

  defp message_pk(%IR.Message{source: {_, resource}}) when is_atom(resource),
    do: Ash.Resource.Info.primary_key(resource)

  defp message_pk(%IR.Message{source: {_, resource, _}}) when is_atom(resource),
    do: Ash.Resource.Info.primary_key(resource)

  defp message_pk(_), do: []

  defp argument?({:argument, _, _, _}), do: true
  defp argument?(_), do: false

  defp ash_name({:argument, _, _, name}), do: name
  defp ash_name({_kind, _resource, name}), do: name
  defp ash_name(_), do: nil

  defp accepted(ctx) do
    pk = if ctx.kind == :update, do: Ash.Resource.Info.primary_key(ctx.resource), else: []
    (Map.get(ctx.action, :accept) || []) ++ pk
  end

  defp fields(nil), do: []
  defp fields(%IR.Message{fields: fields}), do: fields

  defp split_get_by(input, ctx) do
    arguments = Enum.map(ctx.action.arguments, & &1.name)
    by = for name <- ctx.config.get_by || [], name not in arguments, do: name
    {input |> Map.take(by) |> cast_attributes!(ctx), Map.drop(input, by)}
  end

  # identifying values are cast up front so malformed ones are INVALID_ARGUMENT, not NOT_FOUND
  defp cast_attributes!(values, ctx) do
    Enum.map(values, fn {name, value} ->
      attribute = Ash.Resource.Info.attribute(ctx.resource, name)

      case Ash.Type.cast_input(attribute.type, value, attribute.constraints) do
        {:ok, cast} -> {name, cast}
        _ -> raise invalid(name, [], "is invalid")
      end
    end)
  end

  defp split_primary_key(input, ctx) do
    pk = Ash.Resource.Info.primary_key(ctx.resource)

    case Map.split(input, pk) do
      {values, rest} when map_size(values) == length(pk) ->
        {cast_attributes!(values, ctx), rest}

      _ ->
        Masks.invalid!(Enum.map_join(pk, ",", &to_string/1), "is required")
    end
  end

  defp fetch_record!(ctx, pk) do
    read = Ash.Resource.Info.primary_action!(ctx.resource, :read)

    ctx.resource
    |> Ash.Query.for_read(read.name, %{}, Context.input_opts(ctx))
    |> Ash.Query.do_filter(pk)
    |> Ash.read_one(Context.call_opts(ctx))
    |> case do
      {:ok, nil} -> not_found!(ctx, pk)
      {:ok, record} -> record
      {:error, error} -> raise error
    end
  end

  defp not_found!(ctx, by) do
    raise Ash.Error.Query.NotFound.exception(resource: ctx.resource, primary_key: Map.new(by))
  end

  defp decode_chunk(chunk, ctx) do
    Enum.reduce(chunk, {[], []}, fn request, {inputs, errors} ->
      try do
        {[decode_input!(request, ctx, nil) | inputs], errors}
      rescue
        error -> {inputs, [status(error, ctx) | errors]}
      end
    end)
    |> then(fn {inputs, errors} -> {Enum.reverse(inputs), Enum.reverse(errors)} end)
  end

  defp bulk_create([], _ctx), do: {0, []}

  defp bulk_create(inputs, ctx) do
    opts =
      ctx
      |> Context.call_opts()
      |> Keyword.delete(:timeout)
      |> Keyword.merge(
        context: Context.input_opts(ctx)[:context],
        return_errors?: true,
        stop_on_error?: false,
        return_records?: false,
        sorted?: false
      )

    result = Ash.bulk_create(inputs, ctx.resource, ctx.action.name, opts)
    errors = Enum.map(result.errors || [], &status(&1, ctx))
    {length(inputs) - (result.error_count || 0), errors}
  end

  defp status(error, ctx) do
    rpc_error = to_rpc_error(error, ctx)

    struct(AshGrpc.Server.StatusProto.module(),
      code: rpc_error.status,
      message: rpc_error.message,
      details: rpc_error.details
    )
  end

  ## Replies

  @doc """
  Encodes a record with the record message of the rpc's resource (for `AshGrpc.Server.RpcHandler`
  implementations).
  """
  @spec encode_record(term(), Context.t()) :: {:ok, struct()} | {:error, term()}
  def encode_record(record, %Context{} = ctx),
    do: Codec.encode_record(record, ctx.record, ctx.schema)

  defp encode_record!(record, ctx) do
    case encode_record(record, ctx) do
      {:ok, struct} -> struct
      {:error, reason} -> raise encode_error(reason, ctx)
    end
  end

  defp reply_record!(record, %Context{output: nil} = ctx), do: external_reply(record, ctx)

  defp reply_record!(record, ctx) do
    case Codec.encode_record(record, ctx.output, ctx.schema) do
      {:ok, struct} -> struct
      {:error, reason} -> raise encode_error(reason, ctx)
    end
  end

  defp reply_value!(value, %Context{} = ctx) do
    action = ctx.action

    case Enum.find(fields(ctx.output), &(&1.source == {:special, :value})) do
      nil when ctx.rpc.output == @empty ->
        empty()

      nil ->
        value
        |> Codec.encode(action.returns, action.constraints, {:message, ctx.rpc.output},
          schema: ctx.schema
        )
        |> case do
          {:ok, nil} -> struct(ctx.output_module)
          {:ok, struct} -> struct
          {:error, reason} -> raise encode_error(reason, ctx)
        end

      field ->
        case Codec.encode(value, action.returns, action.constraints, field.type,
               schema: ctx.schema
             ) do
          {:ok, encoded} ->
            struct(ctx.output_module, [{String.to_existing_atom(field.name), encoded}])

          {:error, reason} ->
            raise encode_error(reason, ctx)
        end
    end
  end

  # hand-written response modules (`response_message: Module`): fields are copied by name
  defp external_reply(record, ctx) do
    module = ctx.output_module

    values =
      for {_number, %{name_atom: name}} <- module.__message_props__().field_props,
          value = Map.get(record, name),
          plain?(value),
          do: {name, value}

    struct(module, values)
  end

  defp plain?(value) when is_binary(value) or is_number(value) or is_boolean(value), do: true
  defp plain?(values) when is_list(values), do: Enum.all?(values, &plain?/1)
  defp plain?(_), do: false

  defp special_struct(%Context{output: %IR.Message{} = output} = ctx, values) do
    fields =
      for %IR.Field{name: name, source: {:special, key}} <- output.fields,
          Map.has_key?(values, key),
          do: {String.to_existing_atom(name), Map.fetch!(values, key)}

    struct(ctx.output_module, fields)
  end

  defp special_struct(ctx, _values) do
    raise GRPC.RPCError,
      status: GRPC.Status.unimplemented(),
      message: "#{ctx.rpc.name}: a hand-written response message requires a `handler:`"
  end

  defp empty, do: %Google.Protobuf.Empty{}

  # The connection process sends replies asynchronously; wait while it is behind so a slow
  # client throttles `Ash.stream!/2` instead of filling the mailbox.
  defp await_capacity(%{payload: %{pid: pid}} = stream) when is_pid(pid) do
    case Process.info(pid, :message_queue_len) do
      {:message_queue_len, len} when len > @max_pending_replies ->
        Process.sleep(1)
        await_capacity(stream)

      _ ->
        :ok
    end
  end

  defp await_capacity(_stream), do: :ok

  ## Errors

  defp to_rpc_error(error, ctx) do
    opts =
      case ctx.settings.show_raised_errors? do
        nil -> [message: ctx.input]
        show? -> [message: ctx.input, show_raised_errors?: show?]
      end

    AshGrpc.Error.to_rpc_error(error, opts)
  end

  defp codec_error({:invalid_value, _value, _type, reason, path}) do
    {field, path} = List.pop_at(path, -1)
    invalid(field, path, reason)
  end

  defp codec_error({:invalid_value, _value, _type, reason}), do: invalid(nil, [], reason)
  defp codec_error(other), do: invalid(nil, [], other)

  defp invalid(field, path, reason) do
    message = if is_binary(reason), do: reason, else: inspect(reason)

    Ash.Error.Invalid.exception(
      errors: [
        Ash.Error.Changes.InvalidArgument.exception(field: field, path: path, message: message)
      ]
    )
  end

  defp encode_error(reason, ctx) do
    Ash.Error.Unknown.exception(
      errors: [
        Ash.Error.Unknown.UnknownError.exception(
          error: "#{ctx.rpc.name}: cannot encode the reply: #{inspect(reason)}"
        )
      ]
    )
  end
end
