defmodule AshGrpc.Proto.Import.Naming do
  @moduledoc """
  Elixir module names for imported proto entities, following the
  `protoc-gen-elixir` conventions so imported code is interchangeable with code
  generated by `protoc --elixir_out`:

    * the package is camelized segment by segment (`acme.billing.v1` → `Acme.Billing.V1`),
    * nested names are appended and camelized (`Invoice.Item` → `Acme.Billing.V1.Invoice.Item`),
    * `:module_prefix` **replaces** the package (`module_prefix: MyApp.Proto` →
      `MyApp.Proto.Invoice.Item`), exactly like the `module_prefix` plugin option,
    * `:package_prefix` is **prepended** to the package (`package_prefix: "my_app.proto"` →
      `MyApp.Proto.Acme.Billing.V1.Invoice.Item`), like the `package_prefix` plugin option,
    * a service maps to its `GRPC.Service` module `<Package>.<Service>.Service`.
  """

  @identifier ~r/\A[A-Za-z_][A-Za-z0-9_]*\z/

  @doc """
  Module for a message/enum/service named `names` (outermost first) inside `package`.

  Raises `ArgumentError` when a name segment is not a valid proto identifier, so
  malformed descriptors can never inject arbitrary module names.
  """
  @spec module(String.t() | nil, [String.t()], Keyword.t()) :: module()
  def module(package, names, opts \\ []) do
    (prefix_segments(package, opts) ++ names)
    |> Enum.map(&camelize!/1)
    |> Module.concat()
  end

  @doc "The `GRPC.Service` module of a service (`<Package>.<Service>.Service`)."
  @spec service_module(String.t() | nil, String.t(), Keyword.t()) :: module()
  def service_module(package, name, opts \\ []), do: module(package, [name, "Service"], opts)

  @doc """
  Module of a type that lives in a package shipped by a dependency (well-known
  types from `protobuf`, `google.type.*`/`google.rpc.*`/`google.api.*` from
  `googleapis`). Those libraries use unprefixed `protoc-gen-elixir` names, so the
  module is the camelized full name.
  """
  @spec external_module(String.t()) :: module()
  def external_module(full_name) do
    AshGrpc.Proto.WellKnown.module(full_name) ||
      full_name |> String.split(".") |> Enum.map(&camelize!/1) |> Module.concat()
  end

  @doc "Default proto3 JSON name of a field (the algorithm `protoc` uses)."
  @spec default_json_name(String.t()) :: String.t()
  def default_json_name(name) do
    {acc, _} =
      name
      |> String.graphemes()
      |> Enum.reduce({[], false}, fn
        "_", {acc, _} -> {acc, true}
        char, {acc, true} -> {[String.upcase(char) | acc], false}
        char, {acc, false} -> {[char | acc], false}
      end)

    acc |> Enum.reverse() |> Enum.join()
  end

  defp prefix_segments(package, opts) do
    prefix =
      case {opts[:module_prefix], opts[:package_prefix]} do
        {nil, nil} -> package
        {nil, package_prefix} -> join([package_prefix, package])
        {module_prefix, _} -> prefix_string(module_prefix)
      end

    split(prefix)
  end

  defp prefix_string(prefix) when is_atom(prefix),
    do: prefix |> Atom.to_string() |> String.replace_prefix("Elixir.", "")

  defp prefix_string(prefix) when is_binary(prefix), do: prefix

  defp join(parts), do: parts |> Enum.reject(&(&1 in [nil, ""])) |> Enum.join(".")

  defp split(nil), do: []
  defp split(""), do: []
  defp split(name), do: String.split(name, ".")

  defp camelize!(segment) do
    if Regex.match?(@identifier, segment) do
      Macro.camelize(segment)
    else
      raise ArgumentError, "invalid protobuf identifier #{inspect(segment)}"
    end
  end
end
