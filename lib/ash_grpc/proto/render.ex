defmodule AshGrpc.Proto.Render do
  @moduledoc """
  Renders `AshGrpc.Proto.IR.File` structs into `.proto` source text.

  The output is deterministic (the same IR always yields byte-identical text),
  accepted by `protoc` and laid out the way `buf format` prints it, so running
  `buf format` over generated files is a no-op.

  Layout of a rendered file:

      // <header>                    (optional, `:header` option)

      // <file doc>
      syntax = "proto3";

      package my.pkg.v1;

      import "google/protobuf/timestamp.proto";
      import public "my/pkg/v1/shared.proto";

      option go_package = "...";

      service ...                     (services, then messages, then enums;
      message ...                      each group in IR order)
      enum ...

  Details:

    * imports are de-duplicated and sorted by path; an import listed in
      `public_imports` is printed as `import public`
    * docs are printed as `//` comments right above the element they document
    * inside a message: options, reserved numbers, reserved names, fields (a
      oneof block is printed where its first field appears), nested messages,
      nested enums
    * type references are printed relative to the file package when that is
      unambiguous (`User`, `User.Address`), fully qualified otherwise
      (`google.protobuf.Timestamp`), and with a leading dot when even the full
      name would be shadowed by an enclosing scope (`.google.protobuf.Timestamp`)
    * `deprecated?: true` and `idempotency_level` are printed as the matching
      standard options; an explicit `json_name` is printed only when it differs
      from the protoc default
    * option values: strings are quoted, atoms are identifiers (enum constants),
      booleans/numbers as-is, maps (and lists inside maps) as aggregate
      text-format literals (`{a: 1 b: "x"}`) with sorted keys
    * reserved numbers are sorted, ranges print as `9 to 11` / `100 to max`
    * proto2: fields without a label are printed `optional`; `required` and
      `default` are supported. `required` in proto3 raises `ArgumentError`.
    * editions (`{:edition, "2023"}`) are rendered best-effort: `edition = "...";`,
      no `optional`/`required` keywords and unquoted reserved names. Field
      presence features are not modelled by the IR.

  Every identifier is validated (`[A-Za-z_][A-Za-z0-9_]*`, dotted for
  packages/full names) so IR built from untrusted input cannot inject text.
  """

  alias AshGrpc.Proto.IR
  require IR

  @indent "  "
  @ident ~r/\A[A-Za-z_][A-Za-z0-9_]*\z/
  @dotted ~r/\A[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*\z/
  @option_name ~r/\A(\([A-Za-z_.][A-Za-z0-9_.]*\)|[A-Za-z_][A-Za-z0-9_]*)(\.(\([A-Za-z_.][A-Za-z0-9_.]*\)|[A-Za-z_][A-Za-z0-9_]*))*\z/

  @doc """
  Renders a file. Output is deterministic, `buf format`-compatible and
  accepted by `protoc`.

  Options:

    * `:header` – a comment placed at the top (e.g. "Code generated by AshGrpc. DO NOT EDIT.").
      Multi-line strings become multiple comment lines.

  Raises `ArgumentError` on IR that cannot be rendered (invalid identifiers,
  `required` in proto3, unsupported option values).
  """
  @spec render(IR.File.t(), Keyword.t()) :: iodata()
  def render(%IR.File{} = file, opts \\ []) do
    ctx = %{
      syntax: file.syntax,
      package: validate_package!(file.package),
      top_level: MapSet.new(Enum.map(file.messages, & &1.name) ++ Enum.map(file.enums, & &1.name))
    }

    sections =
      [
        header(opts[:header]),
        [comment(file.doc, ""), syntax_line(file.syntax)],
        package_line(ctx.package),
        imports(file),
        options_block(file.options, "")
      ] ++
        Enum.map(file.services, &service(&1, ctx)) ++
        Enum.map(file.messages, &message(&1, ctx, [], "")) ++
        Enum.map(file.enums, &enum(&1, ctx, ""))

    sections
    |> Enum.reject(&empty?/1)
    |> Enum.intersperse("\n")
  end

  # -- file level ---------------------------------------------------------------------------

  defp header(nil), do: []
  defp header(text), do: comment(text, "")

  defp syntax_line(:proto3), do: ~s(syntax = "proto3";\n)
  defp syntax_line(:proto2), do: ~s(syntax = "proto2";\n)
  defp syntax_line({:edition, edition}), do: ["edition = ", quote_string(edition), ";\n"]

  defp syntax_line(other),
    do: raise(ArgumentError, "unsupported syntax: #{inspect(other)}")

  defp package_line(nil), do: []
  defp package_line(package), do: ["package ", package, ";\n"]

  defp imports(%IR.File{imports: imports, public_imports: public}) do
    public = MapSet.new(public)

    (imports ++ MapSet.to_list(public))
    |> Enum.uniq()
    |> Enum.sort()
    |> Enum.map(fn path ->
      keyword = if MapSet.member?(public, path), do: "import public ", else: "import "
      [keyword, quote_string(path), ";\n"]
    end)
  end

  defp options_block(options, indent) do
    Enum.map(options, fn option ->
      [indent, "option ", option_assignment(option, indent), ";\n"]
    end)
  end

  # -- services -----------------------------------------------------------------------------

  defp service(%IR.Service{} = service, ctx) do
    body =
      [options_block(service.options, @indent)] ++ Enum.map(service.rpcs, &rpc(&1, ctx))

    [
      comment(service.doc, ""),
      "service ",
      validate_ident!(service.name, "service name"),
      block(body, "")
    ]
  end

  defp rpc(%IR.Rpc{} = rpc, ctx) do
    signature = [
      "rpc ",
      validate_ident!(rpc.name, "rpc name"),
      "(",
      if(rpc.client_streaming?, do: "stream ", else: ""),
      type_ref(rpc.input, ctx, []),
      ") returns (",
      if(rpc.server_streaming?, do: "stream ", else: ""),
      type_ref(rpc.output, ctx, []),
      ")"
    ]

    options =
      deprecated_option(rpc.deprecated?, rpc.options) ++
        idempotency_option(rpc.idempotency_level, rpc.options) ++ rpc.options

    body =
      case options do
        [] -> ";\n"
        options -> [" {\n", options_block(options, @indent <> @indent), @indent, "}\n"]
      end

    [comment(rpc.doc, @indent), @indent, signature, body]
  end

  defp idempotency_option(nil, _options), do: []

  defp idempotency_option(level, options) do
    if has_option?(options, "idempotency_level") do
      []
    else
      value =
        case level do
          :no_side_effects -> :NO_SIDE_EFFECTS
          :idempotent -> :IDEMPOTENT
          :idempotency_unknown -> :IDEMPOTENCY_UNKNOWN
          other -> raise ArgumentError, "unsupported idempotency_level: #{inspect(other)}"
        end

      [%IR.Option{name: "idempotency_level", value: value}]
    end
  end

  # -- messages -----------------------------------------------------------------------------

  defp message(%IR.Message{} = message, ctx, scopes, indent) do
    validate_ident!(message.name, "message name")
    scopes = scopes ++ [message]
    inner = indent <> @indent

    body = [
      options_block(message.options, inner),
      [
        reserved_numbers(message.reserved_numbers, inner),
        reserved_names(message.reserved_names, inner, ctx)
      ],
      fields(message, ctx, scopes, inner)
    ]

    nested =
      Enum.map(message.nested_messages, &message(&1, ctx, scopes, inner)) ++
        Enum.map(message.nested_enums, &enum(&1, ctx, inner))

    [
      comment(message.doc, indent),
      indent,
      "message ",
      message.name,
      block(body ++ nested, indent)
    ]
  end

  defp fields(%IR.Message{fields: fields, oneofs: oneofs}, ctx, scopes, indent) do
    oneofs_by_name = Map.new(oneofs, &{&1.name, &1})

    {lines, _seen} =
      Enum.flat_map_reduce(fields, MapSet.new(), fn field, seen ->
        cond do
          is_nil(field.oneof) ->
            {[field(field, ctx, scopes, indent, true)], seen}

          MapSet.member?(seen, field.oneof) ->
            {[], seen}

          true ->
            oneof = Map.get(oneofs_by_name, field.oneof, %IR.Oneof{name: field.oneof})
            members = Enum.filter(fields, &(&1.oneof == field.oneof))
            {[oneof(oneof, members, ctx, scopes, indent)], MapSet.put(seen, field.oneof)}
        end
      end)

    lines
  end

  defp oneof(%IR.Oneof{} = oneof, members, ctx, scopes, indent) do
    inner = indent <> @indent

    [
      comment(oneof.doc, indent),
      indent,
      "oneof ",
      validate_ident!(oneof.name, "oneof name"),
      " {\n",
      options_block(oneof.options, inner),
      Enum.map(members, &field(&1, ctx, scopes, inner, false)),
      indent,
      "}\n"
    ]
  end

  defp field(%IR.Field{} = field, ctx, scopes, indent, label?) do
    validate_ident!(field.name, "field name")

    unless is_integer(field.number) and field.number > 0 do
      raise ArgumentError,
            "field #{field.name} has no valid number (#{inspect(field.number)}); " <>
              "assign numbers with AshGrpc.Proto.Lock.assign/2 before rendering"
    end

    options =
      json_name_option(field) ++
        default_option(field) ++
        deprecated_option(field.deprecated?, field.options) ++ field.options

    [
      comment(field.doc, indent),
      indent,
      if(label?, do: label(field, ctx), else: ""),
      field_type(field.type, ctx, scopes),
      " ",
      field.name,
      " = ",
      Integer.to_string(field.number),
      inline_options(options, indent),
      ";\n"
    ]
  end

  defp label(%IR.Field{type: {:map, _, _}}, _ctx), do: ""

  defp label(%IR.Field{label: label, name: name}, %{syntax: syntax}) do
    case {syntax, label} do
      {_, :repeated} ->
        "repeated "

      {{:edition, _}, _} ->
        ""

      {:proto2, :required} ->
        "required "

      {:proto2, _} ->
        "optional "

      {:proto3, :optional} ->
        "optional "

      {:proto3, nil} ->
        ""

      {:proto3, :required} ->
        raise ArgumentError, "field #{name}: `required` is not allowed in proto3"

      {_, other} ->
        raise ArgumentError, "field #{name}: unsupported label #{inspect(other)}"
    end
  end

  defp field_type({:map, key, value}, ctx, scopes) do
    unless IR.is_scalar(key) and key not in [:double, :float, :bytes] do
      raise ArgumentError, "invalid map key type: #{inspect(key)}"
    end

    ["map<", Atom.to_string(key), ", ", field_type(value, ctx, scopes), ">"]
  end

  defp field_type({kind, name}, ctx, scopes) when kind in [:message, :enum],
    do: type_ref(name, ctx, scopes)

  defp field_type(scalar, _ctx, _scopes) when IR.is_scalar(scalar), do: Atom.to_string(scalar)

  defp field_type(other, _ctx, _scopes),
    do: raise(ArgumentError, "unsupported field type: #{inspect(other)}")

  defp json_name_option(%IR.Field{json_name: nil}), do: []

  defp json_name_option(%IR.Field{json_name: json_name, name: name, options: options}) do
    if json_name == default_json_name(name) or has_option?(options, "json_name"),
      do: [],
      else: [%IR.Option{name: "json_name", value: json_name}]
  end

  defp default_option(%IR.Field{default: nil}), do: []

  defp default_option(%IR.Field{default: default, options: options}) do
    if has_option?(options, "default"),
      do: [],
      else: [%IR.Option{name: "default", value: default}]
  end

  defp deprecated_option(true, options) do
    if has_option?(options, "deprecated"),
      do: [],
      else: [%IR.Option{name: "deprecated", value: true}]
  end

  defp deprecated_option(_, _options), do: []

  # buf format keeps a single option inline and puts several on their own lines.
  defp inline_options([], _indent), do: []
  defp inline_options([option], indent), do: [" [", option_assignment(option, indent), "]"]

  defp inline_options(options, indent) do
    inner = indent <> @indent

    [
      " [\n",
      Enum.map_intersperse(options, ",\n", &[inner, option_assignment(&1, inner)]),
      "\n",
      indent,
      "]"
    ]
  end

  # -- enums --------------------------------------------------------------------------------

  defp enum(%IR.Enum{} = enum, ctx, indent) do
    validate_ident!(enum.name, "enum name")
    inner = indent <> @indent

    options =
      if enum.allow_alias? and not has_option?(enum.options, "allow_alias"),
        do: [%IR.Option{name: "allow_alias", value: true} | enum.options],
        else: enum.options

    body = [
      options_block(options, inner),
      [
        reserved_numbers(enum.reserved_numbers, inner),
        reserved_names(enum.reserved_names, inner, ctx)
      ],
      Enum.map(enum.values, &enum_value(&1, inner))
    ]

    [comment(enum.doc, indent), indent, "enum ", enum.name, block(body, indent)]
  end

  defp enum_value(%IR.EnumValue{} = value, indent) do
    validate_ident!(value.name, "enum value name")

    unless is_integer(value.number) do
      raise ArgumentError, "enum value #{value.name} has no number"
    end

    options = deprecated_option(value.deprecated?, value.options) ++ value.options

    [
      comment(value.doc, indent),
      indent,
      value.name,
      " = ",
      Integer.to_string(value.number),
      inline_options(options, indent),
      ";\n"
    ]
  end

  # -- reserved -----------------------------------------------------------------------------

  defp reserved_numbers([], _indent), do: []

  defp reserved_numbers(numbers, indent) do
    ranges =
      numbers
      |> Enum.map(fn
        {from, to} -> {from, to}
        number when is_integer(number) -> {number, number}
      end)
      |> Enum.uniq()
      |> Enum.sort_by(fn {from, to} -> {from, if(to == :max, do: :infinity, else: to)} end)
      |> Enum.map(fn
        {n, n} -> Integer.to_string(n)
        {from, :max} -> [Integer.to_string(from), " to max"]
        {from, to} -> [Integer.to_string(from), " to ", Integer.to_string(to)]
      end)

    [indent, "reserved ", Enum.intersperse(ranges, ", "), ";\n"]
  end

  defp reserved_names([], _indent, _ctx), do: []

  defp reserved_names(names, indent, ctx) do
    names =
      names
      |> Enum.uniq()
      |> Enum.sort()
      |> Enum.map(fn name ->
        validate_ident!(name, "reserved name")
        if match?({:edition, _}, ctx.syntax), do: name, else: quote_string(name)
      end)

    [indent, "reserved ", Enum.intersperse(names, ", "), ";\n"]
  end

  # -- type references ----------------------------------------------------------------------

  # Prints a type reference as short as protoc's scoping rules allow without
  # ambiguity. `scopes` are the enclosing messages (outermost first).
  defp type_ref(full_name, ctx, scopes) do
    validate_dotted!(full_name, "type name")

    case relative_name(full_name, ctx.package) do
      {:local, relative} ->
        relative
        |> suffixes()
        |> Enum.find("." <> full_name, &(not shadowed?(&1, full_name, ctx, scopes)))

      :foreign ->
        if shadowed?(full_name, full_name, ctx, scopes), do: "." <> full_name, else: full_name
    end
  end

  # "A.B.C" -> ["C", "B.C", "A.B.C"]
  defp suffixes(name) do
    segments = String.split(name, ".")

    Enum.map(1..length(segments)//1, fn count ->
      segments |> Enum.take(-count) |> Enum.join(".")
    end)
  end

  defp relative_name(full_name, package) when package in [nil, ""], do: {:local, full_name}

  defp relative_name(full_name, package) do
    prefix = package <> "."

    if String.starts_with?(full_name, prefix),
      do: {:local, String.replace_prefix(full_name, prefix, "")},
      else: :foreign
  end

  # protoc resolves the first segment of a name from the innermost scope outwards and
  # stops at the first symbol it finds. The printed name is safe when that symbol is the
  # one we mean. Known symbols: nested types of enclosing messages, top-level types of
  # this file, the package and its parents, and the referenced type itself.
  defp shadowed?(printed, full_name, ctx, scopes) do
    [first | _] = String.split(printed, ".")
    expected = String.replace_suffix(full_name, String.replace_prefix(printed, first, ""), "")

    message_scopes =
      scopes
      |> Enum.reverse()
      |> Enum.map(fn scope ->
        {scope.full_name <> "." <> first, first in nested_names(scope)}
      end)

    package_scopes =
      Enum.map(package_scopes(ctx.package), fn scope ->
        candidate = IR.full_name(scope, first)
        {candidate, MapSet.member?(ctx.top_level, first) and scope == ctx.package}
      end)

    found =
      Enum.find_value(message_scopes ++ package_scopes, fn {candidate, defined?} ->
        if defined? or candidate == expected or package?(candidate, ctx.package), do: candidate
      end)

    found != expected
  end

  defp nested_names(%IR.Message{} = message),
    do: Enum.map(message.nested_messages, & &1.name) ++ Enum.map(message.nested_enums, & &1.name)

  # "a.b.c" -> ["a.b.c", "a.b", "a", nil]
  defp package_scopes(nil), do: [nil]

  defp package_scopes(package) do
    segments = String.split(package, ".")

    Enum.map(length(segments)..1//-1, fn count ->
      segments |> Enum.take(count) |> Enum.join(".")
    end) ++ [nil]
  end

  defp package?(_candidate, nil), do: false

  defp package?(candidate, package),
    do: package == candidate or String.starts_with?(package, candidate <> ".")

  # -- options ------------------------------------------------------------------------------

  defp option_assignment(%IR.Option{name: name, value: value}, indent) do
    unless is_binary(name) and Regex.match?(@option_name, name) do
      raise ArgumentError, "invalid option name: #{inspect(name)}"
    end

    [name, " = ", constant(value, indent)]
  end

  defp has_option?(options, name), do: Enum.any?(options, &(&1.name == name))

  @doc """
  Renders an option value as a proto constant (see the module docs for the
  supported values). `indent` is the indentation of the line the constant
  starts on (aggregates span several lines).
  """
  @spec constant(term(), String.t()) :: iodata()
  def constant(value, indent \\ "")
  def constant(value, _indent) when is_binary(value), do: quote_string(value)
  def constant(value, _indent) when is_boolean(value), do: Atom.to_string(value)
  def constant(value, _indent) when is_integer(value), do: Integer.to_string(value)
  def constant(value, _indent) when is_float(value), do: float_to_string(value)
  def constant(:inf, _indent), do: "inf"
  def constant(:"-inf", _indent), do: "-inf"
  def constant(:nan, _indent), do: "nan"

  def constant(value, _indent) when is_atom(value) and not is_nil(value) do
    string = Atom.to_string(value)

    unless Regex.match?(@ident, string) do
      raise ArgumentError, "invalid enum constant in option: #{inspect(value)}"
    end

    string
  end

  def constant(value, indent) when is_map(value) and not is_struct(value) do
    inner = indent <> @indent

    entries =
      value
      |> Enum.map(fn {key, val} -> {aggregate_key(key), val} end)
      |> Enum.sort_by(&elem(&1, 0))
      |> Enum.map(fn {key, val} -> [inner, key, ": ", aggregate_value(val, inner), "\n"] end)

    case entries do
      [] -> "{}"
      entries -> ["{\n", entries, indent, "}"]
    end
  end

  def constant(value, _indent),
    do: raise(ArgumentError, "unsupported option value: #{inspect(value)}")

  defp aggregate_value(list, indent) when is_list(list),
    do: ["[", Enum.map_intersperse(list, ", ", &aggregate_value(&1, indent)), "]"]

  defp aggregate_value(value, indent), do: constant(value, indent)

  defp aggregate_key(key) when is_atom(key), do: aggregate_key(Atom.to_string(key))

  defp aggregate_key(key) when is_binary(key) do
    if Regex.match?(@ident, key) or Regex.match?(~r/\A\[[A-Za-z_][A-Za-z0-9_.\/]*\]\z/, key),
      do: key,
      else: raise(ArgumentError, "invalid aggregate option key: #{inspect(key)}")
  end

  defp aggregate_key(key),
    do: raise(ArgumentError, "invalid aggregate option key: #{inspect(key)}")

  # Elixir prints exponents as `1.0e20`, which protoc accepts.
  defp float_to_string(value), do: Float.to_string(value)

  # -- helpers ------------------------------------------------------------------------------

  @doc """
  protoc's default `json_name`: underscores are dropped and the following
  letter is upper-cased (`foo_bar` → `fooBar`).
  """
  @spec default_json_name(String.t()) :: String.t()
  def default_json_name(name) do
    {chars, _} =
      name
      |> String.graphemes()
      |> Enum.flat_map_reduce(false, fn
        "_", _upper? -> {[], true}
        char, true -> {[String.upcase(char)], false}
        char, false -> {[char], false}
      end)

    Enum.join(chars)
  end

  defp quote_string(string),
    do: [?", for(<<char::utf8 <- string>>, into: "", do: escape_char(char)), ?"]

  defp escape_char(?\\), do: "\\\\"
  defp escape_char(?"), do: "\\\""
  defp escape_char(?\n), do: "\\n"
  defp escape_char(?\r), do: "\\r"
  defp escape_char(?\t), do: "\\t"
  defp escape_char(char) when char < 0x20 or char == 0x7F, do: "\\" <> pad_octal(char)
  defp escape_char(char), do: <<char::utf8>>

  defp pad_octal(char), do: char |> Integer.to_string(8) |> String.pad_leading(3, "0")

  defp comment(nil, _indent), do: []
  defp comment("", _indent), do: []

  defp comment(text, indent) do
    text
    |> String.trim_trailing()
    |> String.split(["\r\n", "\n"])
    |> Enum.map(fn
      "" -> [indent, "//\n"]
      line -> [indent, "// ", String.trim_trailing(line), "\n"]
    end)
  end

  # A `{ ... }` body: non-empty blocks separated by blank lines, `{}` when empty.
  defp block(blocks, indent) do
    case join_blocks(blocks) do
      [] -> " {}\n"
      body -> [" {\n", body, indent, "}\n"]
    end
  end

  # Joins non-empty blocks of a body with a blank line between them.
  defp join_blocks(blocks) do
    blocks
    |> Enum.reject(&empty?/1)
    |> Enum.intersperse("\n")
  end

  defp empty?(iodata), do: IO.iodata_length(iodata) == 0

  defp validate_package!(nil), do: nil
  defp validate_package!(""), do: nil
  defp validate_package!(package), do: validate_dotted!(package, "package")

  defp validate_ident!(name, what) do
    if is_binary(name) and Regex.match?(@ident, name),
      do: name,
      else: raise(ArgumentError, "invalid #{what}: #{inspect(name)}")
  end

  defp validate_dotted!(name, what) do
    if is_binary(name) and Regex.match?(@dotted, name),
      do: name,
      else: raise(ArgumentError, "invalid #{what}: #{inspect(name)}")
  end
end
