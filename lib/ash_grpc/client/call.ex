defmodule AshGrpc.Client.Call do
  @moduledoc """
  Execution of client calls (used by the functions generated by `use AshGrpc.Client` and by
  `AshGrpc.Client.call/4` / `stream/4`).

  Every call:

    1. resolves the rpc in the client's `AshGrpc.Client.RpcTable`,
    2. builds the request struct from a map when needed (`AshGrpc.Client.Request`),
    3. computes an absolute deadline (call `deadline:` or the client default, capped by a
       deadline propagated through `AshGrpc.Client.put_deadline/1`); the remaining time is sent
       as `grpc-timeout` on every attempt,
    4. computes metadata (client `:metadata` merged with call `metadata:`),
    5. runs the attempt(s) under the retry policy (`AshGrpc.Client.Retry`, unary only) inside a
       `[:ash_grpc, :client, :rpc]` telemetry span,
    6. maps errors through `AshGrpc.Client.Errors`.

  ## Call options

    * `:deadline` (or `:timeout`) - deadline in milliseconds for the whole call (all attempts).
    * `:metadata` - map or keyword list merged over the client metadata.
    * `:compression` - `:gzip`, a `GRPC.Compressor` module or `nil` (overrides the client).
    * `:retry` - `false` or a keyword list overriding the client retry policy.
    * `:idempotent` - `true`/`false` to override the rpc's idempotency for this call.
    * `:return_headers` - when `true`, unary calls return `{:ok, response, %{headers: ..., trailers: ...}}`.
    * any other key (e.g. `:actor`, `:tenant`) is available to metadata functions in the
      context's `:opts`.

  ## Telemetry

    * `[:ash_grpc, :client, :rpc, :start]` - measurements `%{system_time, monotonic_time}`,
      metadata `%{client, service, rpc, path, grpc_type}`.
    * `[:ash_grpc, :client, :rpc, :stop]` - measurements `%{duration, monotonic_time}`, metadata
      adds `:status` (snake_case gRPC status, `:ok` on success), `:attempts` and `:error` (the
      `GRPC.RPCError`, when failed).
    * `[:ash_grpc, :client, :rpc, :exception]` - when the call raises.

  For streaming rpcs the span covers opening the stream (and, for client streaming, sending the
  requests and receiving the response), not the consumption of a response stream.
  """

  alias AshGrpc.Client.{Codec, Errors, Request, Retry, RpcTable, Runtime, Sandbox}

  @deadline_key {AshGrpc.Client, :deadline}
  @event [:ash_grpc, :client, :rpc]

  @doc false
  def deadline_key, do: @deadline_key

  @doc "Executes a unary rpc."
  @spec unary(atom(), term(), term(), keyword()) ::
          {:ok, struct()} | {:ok, struct(), map()} | {:error, Exception.t()}
  def unary(client, rpc, request, opts) do
    with {:ok, runtime} <- Runtime.fetch(client),
         {:ok, entry} <- RpcTable.fetch(runtime.table, rpc),
         :ok <- expect_type(entry, [:unary], "call/3", "stream/3"),
         {:ok, request} <- Request.build(entry.request, request) do
      ctx = context(runtime, entry, opts)
      span(ctx, fn -> run_unary(ctx, request) end)
    end
  end

  @doc "Executes a streaming rpc (client, server or bidirectional)."
  @spec stream(atom(), term(), term(), keyword()) ::
          {:ok, Enumerable.t()} | {:ok, struct()} | {:error, Exception.t()}
  def stream(client, rpc, request, opts) do
    with {:ok, runtime} <- Runtime.fetch(client),
         {:ok, entry} <- RpcTable.fetch(runtime.table, rpc),
         :ok <-
           expect_type(
             entry,
             [:client_stream, :server_stream, :bidirectional_stream],
             "stream/3",
             "call/3"
           ),
         {:ok, request} <- stream_request(entry, request) do
      ctx = context(runtime, entry, opts)
      span(ctx, fn -> {attempt_stream(ctx, request), 1} end)
    end
  end

  @doc "Checks out a connected channel of the client."
  @spec channel(atom(), keyword()) :: {:ok, GRPC.Channel.t()} | {:error, term()}
  def channel(client, opts) do
    with {:ok, runtime} <- Runtime.fetch(client) do
      if runtime.config.sandbox do
        {:error, Errors.rpc_error(:unavailable, "client #{inspect(client)} runs in sandbox mode")}
      else
        AshGrpc.Client.Pool.checkout(
          runtime,
          Keyword.get(opts, :timeout, runtime.config.connect_timeout)
        )
      end
    end
  end

  # -- unary -------------------------------------------------------------------------------

  defp run_unary(%{runtime: runtime, entry: entry, opts: opts} = ctx, request) do
    policy = Retry.merge(runtime.config.retry, Keyword.get(opts, :retry))
    idempotent? = idempotent?(runtime, entry, opts)

    Retry.run(policy, idempotent?, ctx.deadline_at, fn _attempt ->
      attempt_unary(ctx, request)
    end)
  end

  defp attempt_unary(ctx, request) do
    with {:ok, remaining} <- remaining(ctx),
         :ok <- check_send_size(ctx, request) do
      if ctx.runtime.config.sandbox do
        ctx |> Sandbox.dispatch(request) |> normalize_unary(ctx)
      else
        network_unary(ctx, request, remaining)
      end
    end
  end

  defp network_unary(ctx, request, remaining) do
    with {:ok, channel} <- AshGrpc.Client.Pool.checkout(ctx.runtime, remaining) do
      ctx
      |> stub_call(channel, request, remaining)
      |> normalize_unary(ctx)
    end
  end

  defp normalize_unary({:ok, response}, ctx), do: Codec.finalize(response, max_receive(ctx))

  defp normalize_unary({:ok, response, headers}, ctx) do
    with {:ok, response} <- Codec.finalize(response, max_receive(ctx)) do
      {:ok, response, headers}
    end
  end

  defp normalize_unary({:error, error}, _ctx), do: {:error, Errors.normalize(error)}
  defp normalize_unary(other, _ctx), do: {:error, Errors.normalize(other)}

  # -- streams -----------------------------------------------------------------------------

  defp stream_request(%{grpc_type: :server_stream} = entry, request),
    do: Request.build(entry.request, request)

  defp stream_request(entry, requests) do
    single_map? = is_map(requests) and not is_struct(requests)

    if Enumerable.impl_for(requests) != nil and not single_map? do
      {:ok, Stream.map(requests, &build!(entry.request, &1))}
    else
      {:error,
       ArgumentError.exception(
         "#{entry.name} is a #{entry.grpc_type} rpc, expected an enumerable of requests"
       )}
    end
  end

  defp build!(module, value) do
    case Request.build(module, value) do
      {:ok, struct} -> struct
      {:error, error} -> raise error
    end
  end

  defp attempt_stream(ctx, request) do
    with {:ok, remaining} <- remaining(ctx) do
      cond do
        not ctx.runtime.config.sandbox ->
          network_stream(ctx, request, remaining)

        ctx.entry.grpc_type == :client_stream ->
          ctx |> Sandbox.dispatch(request) |> normalize_unary(ctx)

        true ->
          ctx |> Sandbox.dispatch(request) |> normalize_stream_result(ctx)
      end
    end
  end

  defp network_stream(ctx, request, remaining) do
    with {:ok, channel} <- AshGrpc.Client.Pool.checkout(ctx.runtime, remaining) do
      run_stream(ctx, channel, request, remaining)
    end
  end

  defp run_stream(%{entry: %{grpc_type: :server_stream}} = ctx, channel, request, remaining) do
    with :ok <- check_send_size(ctx, request) do
      ctx
      |> stub_call(channel, request, remaining)
      |> normalize_stream_result(ctx)
    end
  end

  defp run_stream(%{entry: %{grpc_type: :client_stream}} = ctx, channel, requests, remaining) do
    case stub_call(ctx, channel, nil, remaining) do
      %GRPC.Client.Stream{} = stream ->
        safely(fn ->
          stream = send_all(ctx, stream, requests)
          GRPC.Stub.recv(stream, timeout: remaining(ctx, :value))
        end)
        |> normalize_unary(ctx)

      other ->
        normalize_unary(other, ctx)
    end
  end

  defp run_stream(ctx, channel, requests, remaining) do
    case stub_call(ctx, channel, nil, remaining) do
      %GRPC.Client.Stream{} = stream ->
        caller = self()

        # Requests are sent from a linked process so that responses can be consumed while the
        # request enumerable is still producing.
        spawn_link(fn ->
          Process.put(:"$callers", [caller | Process.get(:"$callers", [])])
          send_all(ctx, stream, requests)
        end)

        stream
        |> GRPC.Stub.recv(timeout: remaining(ctx, :value))
        |> normalize_stream_result(ctx)

      other ->
        normalize_stream_result(other, ctx)
    end
  end

  defp send_all(ctx, stream, requests) do
    stream =
      Enum.reduce(requests, stream, fn request, stream ->
        case check_send_size(ctx, request) do
          :ok -> GRPC.Stub.send_request(stream, request)
          {:error, error} -> raise error
        end
      end)

    GRPC.Stub.end_stream(stream)
  end

  defp normalize_stream_result({:ok, enum}, ctx), do: {:ok, response_stream(enum, ctx)}
  defp normalize_stream_result({:ok, enum, _headers}, ctx), do: {:ok, response_stream(enum, ctx)}

  defp normalize_stream_result({:error, error}, _ctx), do: {:error, Errors.normalize(error)}
  defp normalize_stream_result(other, _ctx), do: {:error, Errors.normalize(other)}

  # Response streams yield plain response structs. An error mid-stream raises the (mapped)
  # exception in the consuming process.
  defp response_stream(enum, ctx) do
    max = max_receive(ctx)

    Stream.flat_map(enum, fn
      {:ok, response} ->
        case Codec.finalize(response, max) do
          {:ok, response} -> [response]
          {:error, error} -> raise map_error(error, ctx)
        end

      {:error, error} ->
        raise map_error(Errors.normalize(error), ctx)

      {:headers, _} ->
        []

      {:trailers, _} ->
        []

      %{__struct__: _} = response ->
        [response]
    end)
  end

  # -- transport ---------------------------------------------------------------------------

  defp stub_call(ctx, channel, request, remaining) do
    %{entry: entry} = ctx
    {_, _, {_, server_stream?}, _} = entry.rpc

    stream = %GRPC.Client.Stream{
      channel: channel,
      service_name: entry.service_name,
      method_name: to_string(entry.name),
      grpc_type: entry.grpc_type,
      path: entry.path,
      rpc: entry.rpc,
      server_stream: server_stream?
    }

    opts =
      [timeout: remaining, metadata: ctx.metadata]
      |> put_if(:compressor, compressor(ctx))
      |> put_if(:codec, if(max_receive(ctx), do: Codec))
      |> put_if(:return_headers, Keyword.get(ctx.opts, :return_headers))

    safely(fn -> GRPC.Stub.call(entry.service, entry.rpc, stream, request, opts) end)
  end

  defp safely(fun) do
    fun.()
  rescue
    error -> {:error, Errors.normalize(error)}
  catch
    :exit, reason -> {:error, Errors.normalize({:exit, reason})}
  end

  defp compressor(ctx) do
    case Keyword.fetch(ctx.opts, :compression) do
      {:ok, nil} -> nil
      {:ok, :gzip} -> GRPC.Compressor.Gzip
      {:ok, module} -> module
      :error -> nil
    end
  end

  defp put_if(opts, _key, nil), do: opts
  defp put_if(opts, key, value), do: Keyword.put(opts, key, value)

  defp check_send_size(%{runtime: %{config: %{max_send_message_size: nil}}}, _request), do: :ok

  defp check_send_size(%{runtime: %{config: %{max_send_message_size: max}}}, request) do
    size = request |> Protobuf.encode_to_iodata() |> IO.iodata_length()

    if size > max do
      {:error,
       Errors.rpc_error(
         :resource_exhausted,
         "request message larger than max (#{size} vs. #{max})"
       )}
    else
      :ok
    end
  end

  defp max_receive(ctx), do: ctx.runtime.config.max_receive_message_size

  # -- context, deadline, metadata ---------------------------------------------------------

  defp context(runtime, entry, opts) do
    now = System.monotonic_time(:millisecond)
    deadline = Keyword.get(opts, :deadline) || Keyword.get(opts, :timeout)
    deadline_at = now + (deadline || runtime.config.deadline)

    deadline_at =
      case Process.get(@deadline_key) do
        inherited when is_integer(inherited) -> min(inherited, deadline_at)
        _ -> deadline_at
      end

    ctx = %{
      runtime: runtime,
      entry: entry,
      opts: opts,
      deadline_at: deadline_at,
      client: runtime.config.name,
      metadata: %{}
    }

    %{ctx | metadata: metadata(ctx)}
  end

  defp remaining(ctx) do
    case remaining(ctx, :value) do
      ms when ms > 0 -> {:ok, ms}
      _ -> {:error, Errors.rpc_error(:deadline_exceeded, "deadline exceeded before sending")}
    end
  end

  defp remaining(ctx, :value), do: ctx.deadline_at - System.monotonic_time(:millisecond)

  defp metadata(ctx) do
    meta_ctx = %{
      client: ctx.client,
      service: ctx.entry.service,
      rpc: ctx.entry.name,
      opts: ctx.opts
    }

    base =
      case ctx.runtime.config.metadata do
        {m, f, a} -> apply(m, f, [meta_ctx | a])
        fun when is_function(fun, 0) -> fun.()
        fun when is_function(fun, 1) -> fun.(meta_ctx)
        static -> static
      end

    base
    |> to_metadata_map()
    |> Map.merge(to_metadata_map(Keyword.get(ctx.opts, :metadata, %{})))
  end

  defp to_metadata_map(nil), do: %{}
  defp to_metadata_map(meta), do: Map.new(meta, fn {k, v} -> {to_string(k), v} end)

  defp idempotent?(runtime, entry, opts) do
    case Keyword.fetch(opts, :idempotent) do
      {:ok, value} -> value == true
      :error -> entry.idempotent? or MapSet.member?(runtime.idempotent, entry.path)
    end
  end

  # -- telemetry & result ------------------------------------------------------------------

  defp span(ctx, fun) do
    meta = %{
      client: ctx.client,
      service: ctx.entry.service,
      rpc: ctx.entry.name,
      path: ctx.entry.path,
      grpc_type: ctx.entry.grpc_type
    }

    :telemetry.span(@event, meta, fn ->
      {result, attempts} = fun.()

      stop_meta =
        case result do
          {:error, %GRPC.RPCError{status: status} = error} ->
            Map.merge(meta, %{status: Errors.status_name(status), error: error})

          _ ->
            Map.put(meta, :status, :ok)
        end

      {map_result(result, ctx), Map.put(stop_meta, :attempts, attempts)}
    end)
  end

  defp map_result({:error, %GRPC.RPCError{} = error}, ctx), do: {:error, map_error(error, ctx)}
  defp map_result(result, _ctx), do: result

  defp map_error(%GRPC.RPCError{} = error, %{runtime: %{config: %{map_errors: false}}}), do: error

  defp map_error(%GRPC.RPCError{} = error, ctx) do
    Errors.from_rpc_error(error,
      client: ctx.client,
      service: ctx.entry.service,
      rpc: ctx.entry.name
    )
  end

  defp expect_type(entry, types, _fun, other_fun) do
    if entry.grpc_type in types do
      :ok
    else
      {:error,
       ArgumentError.exception(
         "#{inspect(entry.service)}.#{entry.name} is a #{entry.grpc_type} rpc, use #{other_fun} instead"
       )}
    end
  end
end
