defmodule AshGrpc.Codegen do
  @moduledoc """
  The codegen pipeline behind `mix ash_grpc.codegen` (and `mix ash.codegen`).

      Lock.load ─► Schema.build_with_lock ─► Diff.diff(snapshots, new)
                     └─► Render.render (with header) ─► .proto files, snapshots, lock (, buf.yaml)

  `plan/1` computes everything without touching the disk and returns an
  `AshGrpc.Codegen.Plan`; `write!/1` applies it. Splitting both keeps `--check` and
  `--dry-run` trivial and makes the pipeline usable from code and tests.

  ## Outputs

    * one `.proto` per domain under `:out` (default `priv/protos`), at the file's import
      path, starting with the `// Code generated by AshGrpc. DO NOT EDIT.` header
    * one JSON snapshot per `.proto` under `:snapshots` (default `priv/grpc/snapshots`), see
      `AshGrpc.Codegen.Snapshot` – the baseline for the next run's breaking-change check
    * the lock file (default `AshGrpc.Proto.Lock.default_path/1`)
    * with `buf: true`, a `buf.yaml` in `:out` (see `buf_yaml/1`)

  Generated `.proto` files that are no longer produced are deleted, but only files that
  start with the header (hand-written protos in the same directory are never touched). Stale
  snapshots are deleted too. When `:domains` is a subset of the application's domains
  (`all_domains?: false`), only files and snapshots that belonged to those domains are
  considered, so generating one domain never deletes the files of another.
  """

  alias AshGrpc.Codegen.{Plan, Snapshot}
  alias AshGrpc.Proto.{Diff, IR, Lock, Render}

  @header "Code generated by AshGrpc. DO NOT EDIT."

  @default_out "priv/protos"
  @default_snapshots Path.join(["priv", "grpc", "snapshots"])

  @googleapis_prefixes ["google/api/", "google/rpc/", "google/type/", "google/longrunning/"]

  @doc "The first line of every generated file."
  @spec header() :: String.t()
  def header, do: @header

  @doc "Default output directory for `.proto` files."
  @spec default_out() :: Path.t()
  def default_out, do: @default_out

  @doc "Default directory of the IR snapshots."
  @spec default_snapshots() :: Path.t()
  def default_snapshots, do: @default_snapshots

  @doc """
  Computes what codegen would write, without touching the disk.

  ## Options

    * `:domains` (required) – domains using `AshGrpc.Domain`
    * `:out` – output directory for `.proto` files (default `#{@default_out}`)
    * `:lock` – lock file path (default `AshGrpc.Proto.Lock.default_path/1`)
    * `:snapshots` – snapshot directory (default `#{@default_snapshots}`)
    * `:buf` – also write `buf.yaml` into `:out` (default `false`)
    * `:all_domains?` – whether `:domains` are all domains of the application, which allows
      deleting generated files of domains that no longer exist (default `true`)
  """
  @spec plan(Keyword.t()) :: {:ok, Plan.t()} | {:error, term()}
  def plan(opts) do
    domains = Keyword.fetch!(opts, :domains)
    out = Keyword.get(opts, :out, @default_out)
    lock_path = Keyword.get_lazy(opts, :lock, fn -> Lock.default_path(nil) end)
    snapshots_dir = Keyword.get(opts, :snapshots, @default_snapshots)
    all_domains? = Keyword.get(opts, :all_domains?, true)

    with {:ok, lock} <- load_lock(lock_path),
         {:ok, schema, lock} <- build(domains, lock),
         {:ok, old_snapshots} <- load_snapshots(snapshots_dir, schema, domains, all_domains?) do
      old = %IR.Schema{files: Enum.map(old_snapshots, fn {_path, snapshot} -> snapshot.file end)}
      changes = Diff.diff(old, schema)

      outputs =
        proto_outputs(schema, out) ++
          snapshot_outputs(schema, snapshots_dir) ++
          [{:lock, lock_path, Lock.encode(lock)}] ++
          buf_outputs(schema, out, opts[:buf])

      files = Enum.map(outputs, &output_file/1)
      generated = MapSet.new(files, &Path.expand(&1.path))

      deletes =
        stale_protos(out, generated, old_snapshots, all_domains?) ++
          stale_snapshots(old_snapshots, generated)

      {:ok,
       %Plan{
         schema: schema,
         lock: lock,
         changes: changes,
         files: files,
         deletes: deletes
       }}
    end
  end

  @doc "Writes the changed files of a plan and deletes its stale files."
  @spec write!(Plan.t()) :: :ok
  def write!(%Plan{} = plan) do
    for %{status: status, path: path, contents: contents} <- plan.files,
        status != :unchanged do
      Elixir.File.mkdir_p!(Path.dirname(path))
      Elixir.File.write!(path, contents)
    end

    Enum.each(plan.deletes, &Elixir.File.rm!(&1.path))
    :ok
  end

  @doc """
  Contents of the `buf.yaml` written with `buf: true`: a v2 module rooted at the output
  directory with `STANDARD` lint and `WIRE_JSON` breaking rules. AIP-style responses (`Get`
  returning the resource, `Delete` returning `google.protobuf.Empty`) are allowed by excepting
  the `RPC_*_STANDARD_NAME`/`RPC_REQUEST_RESPONSE_UNIQUE` rules. Files importing googleapis
  protos (`google/api`, `google/rpc`, `google/type`) add the `buf.build/googleapis/googleapis`
  dependency (run `buf dep update` once to create `buf.lock`).
  """
  @spec buf_yaml(IR.Schema.t()) :: String.t()
  def buf_yaml(%IR.Schema{} = schema) do
    deps =
      if Enum.any?(schema.files, &googleapis?/1),
        do: "deps:\n  - buf.build/googleapis/googleapis\n",
        else: ""

    """
    # #{@header}
    version: v2
    #{deps}lint:
      use:
        - STANDARD
      except:
        - RPC_REQUEST_RESPONSE_UNIQUE
        - RPC_REQUEST_STANDARD_NAME
        - RPC_RESPONSE_STANDARD_NAME
    breaking:
      use:
        - WIRE_JSON
    """
  end

  @doc "Whether a file's contents start with the AshGrpc header (i.e. it was generated)."
  @spec generated?(String.t()) :: boolean()
  def generated?(contents), do: String.starts_with?(contents, "// " <> @header)

  @doc "Formats a plan error for humans."
  @spec format_error(term()) :: String.t()
  def format_error(errors) when is_list(errors),
    do: Enum.map_join(errors, "\n", &format_error/1)

  def format_error(%{__exception__: true} = error), do: Exception.message(error)
  def format_error({:lock, path, reason}), do: "cannot load lock #{path}: #{inspect(reason)}"

  def format_error({:snapshot, path, reason}),
    do: "cannot load snapshot #{path}: #{inspect(reason)}"

  def format_error(other), do: inspect(other)

  # -- pipeline steps -----------------------------------------------------------------------

  defp load_lock(path) do
    case Lock.load(path) do
      {:ok, lock} -> {:ok, lock}
      {:error, reason} -> {:error, {:lock, path, reason}}
    end
  end

  defp build(domains, lock) do
    AshGrpc.Schema.build_with_lock(domains, lock: lock)
  rescue
    error in Lock.ConflictError -> {:error, [error]}
  end

  # With a domain subset, only snapshots of those domains (or of files they still generate,
  # e.g. after a domain module was renamed) are the baseline.
  defp load_snapshots(dir, schema, domains, all_domains?) do
    with {:ok, snapshots} <- Snapshot.load_dir(dir) do
      names = MapSet.new(domains, &inspect/1)
      paths = MapSet.new(schema.files, & &1.path)

      {:ok,
       Enum.filter(snapshots, fn {_, snapshot} ->
         all_domains? or snapshot.domain in names or snapshot.file.path in paths
       end)}
    end
  end

  defp proto_outputs(schema, out) do
    for file <- schema.files do
      header = "#{@header}\nsource: #{domain_label(file)}"

      {:proto, Path.join(out, file.path),
       IO.iodata_to_binary(Render.render(file, header: header))}
    end
  end

  defp snapshot_outputs(schema, dir) do
    for file <- schema.files do
      {:snapshot, Snapshot.path(dir, file.path), Snapshot.encode(file, domain(file))}
    end
  end

  defp buf_outputs(schema, out, true), do: [{:buf, Path.join(out, "buf.yaml"), buf_yaml(schema)}]
  defp buf_outputs(_schema, _out, _buf), do: []

  defp output_file({kind, path, contents}) do
    status =
      case Elixir.File.read(path) do
        {:ok, ^contents} -> :unchanged
        {:ok, _other} -> :updated
        {:error, _} -> :created
      end

    %{kind: kind, path: path, contents: contents, status: status}
  end

  # Generated protos (by header) in `out` that are not produced anymore. With a domain
  # subset, only the files recorded in the snapshots of those domains are candidates.
  defp stale_protos(out, generated, old_snapshots, all_domains?) do
    candidates =
      if all_domains? do
        out |> Path.join("**/*.proto") |> Path.wildcard()
      else
        for {_, snapshot} <- old_snapshots, do: Path.join(out, snapshot.file.path)
      end

    candidates
    |> Enum.uniq()
    |> Enum.sort()
    |> Enum.reject(&MapSet.member?(generated, Path.expand(&1)))
    |> Enum.filter(&generated_file?/1)
    |> Enum.map(&%{kind: :proto, path: &1})
  end

  defp generated_file?(path) do
    case Elixir.File.read(path) do
      {:ok, contents} -> generated?(contents)
      {:error, _} -> false
    end
  end

  defp stale_snapshots(old_snapshots, generated) do
    for {path, _} <- old_snapshots,
        not MapSet.member?(generated, Path.expand(path)),
        do: %{kind: :snapshot, path: path}
  end

  defp domain({:domain, domain}), do: domain
  defp domain(%IR.File{source: source}), do: domain(source)
  defp domain(_), do: nil

  defp domain_label(file) do
    case domain(file) do
      nil -> file.path
      domain -> inspect(domain)
    end
  end

  defp googleapis?(%IR.File{imports: imports, public_imports: public}) do
    Enum.any?(imports ++ public, &String.starts_with?(&1, @googleapis_prefixes))
  end
end
