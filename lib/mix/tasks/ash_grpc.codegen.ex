defmodule Mix.Tasks.AshGrpc.Codegen do
  @shortdoc "Generates .proto files, IR snapshots and the field-number lock for AshGrpc domains"

  @moduledoc """
  Generates `.proto` files for every domain using `AshGrpc.Domain`, updates the field-number
  lock and checks the changes for wire compatibility.

      mix ash_grpc.codegen                 # writes priv/protos/**/*.proto, snapshots and the lock
      mix ash_grpc.codegen --check         # CI: fails on stale output or breaking changes
      mix ash_grpc.codegen --dry-run       # prints what would change, writes nothing

  `mix ash.codegen [name]` runs this task too (Ash extension codegen hook on
  `AshGrpc.Domain`), so the usual `mix ash.codegen --check` CI step covers gRPC as well.

  ## Pipeline

    1. load the lock (`AshGrpc.Proto.Lock.load/1`)
    2. build the IR (`AshGrpc.Schema.build_with_lock/2`), assigning stable field numbers
    3. diff it against the last snapshots (`AshGrpc.Proto.Diff.diff/2`)
    4. render the `.proto` files with a `Code generated by AshGrpc. DO NOT EDIT.` header,
       write the snapshots and the lock, delete generated files that are no longer produced
    5. print the safe and breaking changes

  Breaking changes (see `AshGrpc.Proto.Diff`) abort the run before anything is written,
  unless `--allow-breaking` is given: once the snapshots are rewritten the change is no longer
  visible to `--check`, so accepting it must be a deliberate decision. Removing a field is not
  breaking: its number and name are reserved automatically.

  ## Arguments

  An optional `name` (as for `mix ash.codegen <name>`) is accepted and ignored: protos are
  regenerated as a whole, there are no named migrations.

  ## Options

    * `--check` – write nothing; exit non-zero if any file or the lock would change, or if
      the changes are breaking (unless `--allow-breaking`)
    * `--dry-run` – write nothing; print the pending files, their contents and the changes
    * `--allow-breaking` – accept breaking changes
    * `--out` – output directory for `.proto` files (default `priv/protos`)
    * `--lock` – lock file (default `priv/grpc/ash_grpc.lock.json`)
    * `--snapshots` – snapshot directory (default `priv/grpc/snapshots`)
    * `--domains` – comma-separated domains (default: `config :my_app, ash_domains`, filtered
      to the domains using `AshGrpc.Domain`)
    * `--buf` – also write a minimal `buf.yaml` next to the protos
    * `--quiet` – only print errors

  Options passed by `mix ash.codegen` that do not apply (`--name`, `--dev`, …) are ignored.
  """

  use Mix.Task

  alias AshGrpc.Codegen
  alias AshGrpc.Codegen.Plan
  alias AshGrpc.Proto.Diff

  @switches [
    check: :boolean,
    dry_run: :boolean,
    allow_breaking: :boolean,
    out: :string,
    lock: :string,
    snapshots: :string,
    domains: :string,
    buf: :boolean,
    quiet: :boolean
  ]

  @impl Mix.Task
  def run(argv) do
    {opts, _args, _invalid} =
      argv |> Enum.filter(&is_binary/1) |> OptionParser.parse(switches: @switches)

    Mix.Task.run("compile")

    otp_app = Mix.Project.config()[:app]
    {domains, all_domains?} = domains(opts, otp_app)

    if domains == [] do
      info(opts, "No domains using AshGrpc.Domain found, nothing to generate.")
    else
      domains
      |> plan(opts, otp_app, all_domains?)
      |> execute(opts)
    end
  end

  defp plan(domains, opts, otp_app, all_domains?) do
    plan_opts = [
      domains: domains,
      out: opts[:out] || Codegen.default_out(),
      lock: opts[:lock] || AshGrpc.Proto.Lock.default_path(otp_app),
      snapshots: opts[:snapshots] || Codegen.default_snapshots(),
      buf: opts[:buf] || false,
      all_domains?: all_domains?
    ]

    case Codegen.plan(plan_opts) do
      {:ok, plan} -> plan
      {:error, error} -> Mix.raise("ash_grpc.codegen failed:\n" <> Codegen.format_error(error))
    end
  end

  defp execute(plan, opts) do
    breaking? = Plan.breaking?(plan) and not (opts[:allow_breaking] || false)

    cond do
      opts[:check] -> check!(plan, breaking?)
      opts[:dry_run] -> dry_run(plan, opts)
      breaking? -> Mix.raise(breaking_message(plan))
      true -> write(plan, opts)
    end
  end

  defp check!(plan, breaking?) do
    cond do
      breaking? ->
        Mix.raise(breaking_message(plan))

      Plan.changed?(plan) ->
        Mix.raise("""
        AshGrpc generated files are out of date:

        #{indent(Plan.summary(plan))}

        Changes:
        #{indent(Diff.format(plan.changes))}

        Run `mix ash_grpc.codegen` (or `mix ash.codegen`) and commit the result.
        """)

      true ->
        :ok
    end
  end

  defp dry_run(plan, opts) do
    if Plan.changed?(plan) do
      for %{kind: :proto, path: path, contents: contents} <- Plan.pending_files(plan) do
        info(opts, "#{path}:\n\n#{contents}")
      end

      info(opts, "Would write:\n#{indent(Plan.summary(plan))}")
    else
      info(opts, "AshGrpc generated files are up to date.")
    end

    print_changes(plan, opts)
  end

  defp write(plan, opts) do
    if Plan.changed?(plan) do
      Codegen.write!(plan)
      info(opts, indent(Plan.summary(plan)))
    else
      info(opts, "AshGrpc generated files are up to date.")
    end

    print_changes(plan, opts)
  end

  defp print_changes(%Plan{changes: []}, _opts), do: :ok

  defp print_changes(plan, opts) do
    info(opts, "Changes:\n" <> indent(Diff.format(plan.changes)))
  end

  defp breaking_message(plan) do
    """
    AshGrpc found breaking protobuf changes:

    #{indent(Diff.format(Diff.breaking(plan.changes)))}

    Existing clients may fail to decode messages or call removed rpcs. Make the change
    compatible (add a new field/rpc instead of changing one), or run again with
    `--allow-breaking` to accept it.
    """
  end

  # -- domains ------------------------------------------------------------------------------

  defp domains(opts, otp_app) do
    case opts[:domains] do
      nil ->
        domains =
          otp_app
          |> Application.get_env(:ash_domains, [])
          |> Enum.filter(&grpc_domain?/1)

        {domains, true}

      names ->
        domains =
          names
          |> String.split(",", trim: true)
          |> Enum.map(&String.trim/1)
          |> Enum.map(&Module.concat([&1]))

        case Enum.reject(domains, &grpc_domain?/1) do
          [] -> :ok
          [domain | _] -> Mix.raise("#{inspect(domain)} is not a domain using AshGrpc.Domain")
        end

        {domains, false}
    end
  end

  defp grpc_domain?(module) do
    Code.ensure_loaded?(module) and function_exported?(module, :spark_dsl_config, 0) and
      AshGrpc.Domain in Spark.extensions(module)
  end

  defp info(opts, message), do: unless(opts[:quiet], do: Mix.shell().info(message))

  defp indent(lines) when is_list(lines), do: lines |> Enum.join("\n") |> indent()

  defp indent(text) do
    text |> String.split("\n") |> Enum.map_join("\n", &("  " <> &1))
  end
end
