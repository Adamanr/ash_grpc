defmodule Mix.Tasks.AshGrpc.CodegenTest do
  # global state: Mix shell and the :ash_grpc application env
  use ExUnit.Case, async: false

  alias AshGrpc.Test.Codegen.{Gadgets, Widgets}

  @moduletag :tmp_dir

  @widgets_proto "ashgrpc/test/widgets/v1/widgets.proto"

  setup %{tmp_dir: dir} do
    Mix.shell(Mix.Shell.Process)
    on_exit(fn -> Mix.shell(Mix.Shell.IO) end)

    paths = [
      "--out",
      Path.join(dir, "protos"),
      "--lock",
      Path.join(dir, "lock.json"),
      "--snapshots",
      Path.join(dir, "snapshots")
    ]

    %{paths: paths, dir: dir}
  end

  defp codegen(domains, paths, flags \\ []) do
    Mix.Task.reenable("ash_grpc.codegen")

    Mix.Tasks.AshGrpc.Codegen.run(
      ["--domains", Enum.map_join(List.wrap(domains), ",", &inspect/1)] ++ paths ++ flags
    )
  end

  defp output do
    Stream.repeatedly(fn ->
      receive do
        {:mix_shell, :info, [message]} -> message
      after
        0 -> nil
      end
    end)
    |> Enum.take_while(& &1)
    |> Enum.join("\n")
  end

  defp tree(dir) do
    dir
    |> Path.join("**/*")
    |> Path.wildcard()
    |> Enum.filter(&File.regular?/1)
    |> Map.new(&{Path.relative_to(&1, dir), File.read!(&1)})
  end

  test "generates files and reports a second run as up to date", %{paths: paths, dir: dir} do
    codegen(Widgets.V1, paths)
    out = output()
    assert out =~ "created #{dir}/protos/#{@widgets_proto}"
    assert out =~ "created #{dir}/lock.json"
    assert out =~ "[safe]"
    assert File.exists?(Path.join([dir, "protos", @widgets_proto]))

    codegen(Widgets.V1, paths)
    assert output() =~ "up to date"
  end

  test "--check passes when up to date and fails when output is stale", %{paths: paths, dir: dir} do
    error = assert_raise Mix.Error, fn -> codegen(Widgets.V1, paths, ["--check"]) end
    assert error.message =~ "out of date"
    assert error.message =~ "created #{dir}/protos/#{@widgets_proto}"
    assert tree(dir) == %{}

    codegen(Widgets.V1, paths)
    assert codegen(Widgets.V1, paths, ["--check"]) == :ok

    # a safe change is still a stale output
    error = assert_raise Mix.Error, fn -> codegen(Widgets.V2, paths, ["--check"]) end
    assert error.message =~ "updated #{dir}/lock.json"
    assert error.message =~ "Widget.color"
  end

  test "breaking changes fail --check and abort generation unless allowed", %{
    paths: paths,
    dir: dir
  } do
    codegen(Widgets.V1, paths)
    before = tree(dir)

    error = assert_raise Mix.Error, fn -> codegen(Widgets.V4, paths, ["--check"]) end
    assert error.message =~ "breaking protobuf changes"
    assert error.message =~ "[breaking] ashgrpc.test.widgets.v1.Widget.size"

    error = assert_raise Mix.Error, fn -> codegen(Widgets.V4, paths) end
    assert error.message =~ "--allow-breaking"
    assert tree(dir) == before

    # --check --allow-breaking still fails on the stale output
    error =
      assert_raise Mix.Error, fn ->
        codegen(Widgets.V4, paths, ["--check", "--allow-breaking"])
      end

    assert error.message =~ "out of date"

    codegen(Widgets.V4, paths, ["--allow-breaking"])
    assert output() =~ "[breaking]"
    assert codegen(Widgets.V4, paths, ["--check"]) == :ok
  end

  test "--dry-run prints the pending output and writes nothing", %{paths: paths, dir: dir} do
    codegen(Widgets.V1, paths, ["--dry-run"])
    out = output()

    assert out =~ "// Code generated by AshGrpc. DO NOT EDIT."
    assert out =~ "Would write:"
    assert out =~ "created #{dir}/lock.json"
    assert tree(dir) == %{}
  end

  test "--buf writes buf.yaml and --quiet prints nothing", %{paths: paths, dir: dir} do
    codegen(Widgets.V1, paths, ["--buf", "--quiet"])
    assert output() == ""
    assert File.exists?(Path.join(dir, "protos/buf.yaml"))
  end

  test "default domains come from the :ash_domains config", %{paths: paths, dir: dir} do
    previous = Application.get_env(:ash_grpc, :ash_domains)
    # non-grpc domains are skipped
    Application.put_env(:ash_grpc, :ash_domains, [Gadgets, Ash.Test.NotADomain])

    on_exit(fn ->
      if previous,
        do: Application.put_env(:ash_grpc, :ash_domains, previous),
        else: Application.delete_env(:ash_grpc, :ash_domains)
    end)

    Mix.Task.reenable("ash_grpc.codegen")
    Mix.Tasks.AshGrpc.Codegen.run(paths)
    assert File.exists?(Path.join(dir, "protos/ashgrpc/test/gadgets/v1/gadgets.proto"))

    Application.put_env(:ash_grpc, :ash_domains, [])
    Mix.Task.reenable("ash_grpc.codegen")
    Mix.Tasks.AshGrpc.Codegen.run(paths)
    assert output() =~ "No domains using AshGrpc.Domain"
  end

  test "--domains rejects modules that are not AshGrpc domains", %{paths: paths} do
    assert_raise Mix.Error, ~r/not a domain using AshGrpc.Domain/, fn ->
      codegen(AshGrpc.Test.Codegen.Gadget, paths)
    end
  end

  describe "Ash codegen hook" do
    test "AshGrpc.Domain implements codegen/1 for `mix ash.codegen`" do
      assert function_exported?(AshGrpc.Domain, :codegen, 1)
      refute function_exported?(AshGrpc.Resource, :codegen, 1)
    end

    test "codegen/1 runs ash_grpc.codegen with ash.codegen's arguments", %{
      paths: paths,
      dir: dir
    } do
      # `mix ash.codegen` appends `--name <name>` (nil without a name) and passes `--dev` etc.
      argv = ["--domains", inspect(Widgets.V1) | paths] ++ ["--dev", "--name", nil]

      AshGrpc.Domain.codegen(argv)
      assert File.exists?(Path.join([dir, "protos", @widgets_proto]))

      AshGrpc.Domain.codegen(argv ++ ["--check"])

      assert_raise Mix.Error, ~r/out of date/, fn ->
        AshGrpc.Domain.codegen(["--domains", inspect(Widgets.V2) | paths] ++ ["--check"])
      end
    end

    test "mix ash.codegen --check runs AshGrpc codegen", %{paths: paths} do
      Mix.Task.reenable("ash.codegen")

      assert_raise Mix.Error, ~r/AshGrpc generated files are out of date/, fn ->
        Mix.Tasks.Ash.Codegen.run([
          "add_widgets",
          "--check",
          "--domains",
          inspect(Widgets.V1) | paths
        ])
      end
    end
  end
end
