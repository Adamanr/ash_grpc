defmodule AshGrpc.Proto.RenderProtocTest do
  @moduledoc "Validates rendered output with the real `protoc` and `buf` binaries."
  use ExUnit.Case, async: true

  alias AshGrpc.Proto.IR
  alias AshGrpc.Test.{Protoc, ProtoFixtures}

  @moduletag :protoc
  @moduletag :tmp_dir
  unless Protoc.available?(), do: @moduletag(skip: "protoc is not installed")

  defp files do
    nested_shadowing = %IR.File{
      path: "acme/google/v1/x.proto",
      package: "acme.google.v1",
      imports: ["google/protobuf/timestamp.proto", "acme/shop/v1/shop.proto"],
      messages: [
        %IR.Message{name: "Nothing", full_name: "acme.google.v1.Nothing"},
        %IR.Message{
          name: "A",
          full_name: "acme.google.v1.A",
          nested_messages: [
            %IR.Message{
              name: "Role",
              full_name: "acme.google.v1.A.Role",
              fields: [%IR.Field{name: "x", number: 1, type: :string}]
            }
          ],
          fields: [
            %IR.Field{name: "ts", number: 1, type: {:message, "google.protobuf.Timestamp"}},
            %IR.Field{name: "role", number: 2, type: {:enum, "acme.shop.v1.Role"}},
            %IR.Field{name: "local", number: 3, type: {:message, "acme.google.v1.A.Role"}}
          ]
        }
      ]
    }

    [ProtoFixtures.shop_file(), ProtoFixtures.legacy_file(), nested_shadowing]
  end

  test "protoc accepts the rendered files", %{tmp_dir: dir} do
    paths = Protoc.write_files!(files(), dir, header: "Code generated by AshGrpc. DO NOT EDIT.")
    set = Protoc.descriptor_set!(dir, paths)

    shop = Enum.find(set.file, &(&1.name == "acme/shop/v1/shop.proto"))
    user = Enum.find(shop.message_type, &(&1.name == "User"))

    assert Enum.map(user.field, & &1.number) == Enum.to_list(1..12) ++ [14, 18, 19, 20, 21]

    # type references were resolved to what the IR meant
    x = Enum.find(set.file, &(&1.name == "acme/google/v1/x.proto"))
    [_nothing, a] = x.message_type

    assert Enum.map(a.field, & &1.type_name) == [
             ".google.protobuf.Timestamp",
             ".acme.shop.v1.Role",
             ".acme.google.v1.A.Role"
           ]
  end

  @tag :buf
  test "buf format leaves the output untouched", %{tmp_dir: dir} do
    if Protoc.buf_available?() do
      Protoc.write_files!(files(), dir, header: "Code generated by AshGrpc. DO NOT EDIT.")
      assert Protoc.buf_format_diff(dir) == ""
    end
  end
end
